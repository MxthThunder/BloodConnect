"""
Emergency coordination assistant - rule-based explanation service.

Every sentence is generated from the persisted case, its attempts, events and the active
policy. No external AI service is called, so the application works fully offline. Output
always separates *known facts* from *unknowns*, names the rules that fired, and never
asserts delivery, transfusion compatibility or donor eligibility that the data cannot support.
"""
from django.utils import timezone

from .candidates import rank_candidates
from .constants import (
    AttemptStatus, CaseStatus, EventType, Fulfilment, PENDING_ATTEMPT_STATUSES, TERMINAL_CASE_STATUSES,
)
from .models import EmergencyCase, Experiment

DISCLAIMER = (
    'Explanations are generated by rules from the recorded request, candidate, response and event data. '
    'Accepted volunteers are not confirmed donations or blood units, and nothing here is a medical judgement: '
    'donor eligibility and transfusion compatibility are decided by qualified blood-bank staff.'
)
GENERATED_BY = 'Rule-based explanation service (no external AI service is used)'

QUESTIONS = [
    {'key': 'why_unresolved', 'label': 'Why is this request still unresolved?'},
    {'key': 'why_prioritised', 'label': 'Why did the system prioritise these candidates?'},
    {'key': 'why_expanded', 'label': 'Why was the search expanded (or not)?'},
    {'key': 'missing_information', 'label': 'What information is missing?'},
    {'key': 'stages_completed', 'label': 'Which outreach stages have been completed?'},
    {'key': 'remaining_actions', 'label': 'What actions remain?'},
    {'key': 'strategy_comparison', 'label': 'How did the escalation strategies perform in the simulation?'},
]

_KEYWORDS = [
    ('strategy_comparison', ('compare', 'comparison', 'strateg', 'baseline', 'perform', 'experiment')),
    ('why_prioritised', ('prioriti', 'rank', 'why these', 'score', 'candidate order', 'chosen', 'selected')),
    ('why_expanded', ('expand', 'wider', 'radius', 'escalat', 'stage 2', 'next stage')),
    ('missing_information', ('missing', 'unknown', 'information', 'not know', "don't know", 'data gap')),
    ('stages_completed', ('stage', 'completed', 'batch', 'outreach so far', 'progress')),
    ('remaining_actions', ('action', 'next', 'do now', 'remain', 'should', 'recommend', 'todo', 'to do')),
    ('why_unresolved', ('unresolved', 'still open', 'why is', 'not resolved', 'pending', 'status', 'why')),
]


def route_question(text):
    text = (text or '').lower().strip()
    if not text:
        return None
    for key, words in _KEYWORDS:
        if any(w in text for w in words):
            return key
    return None


class CaseContext:
    def __init__(self, case, now=None):
        self.case = case
        self.now = now or (case.last_evaluated_at if case.is_simulation and case.last_evaluated_at else timezone.now())
        self.policy = case.get_policy()
        self.attempts = list(case.attempts.select_related('batch', 'donor__user', 'sim_donor'))
        self.events = list(case.events.all())
        self._rank = None

    @property
    def rank(self):
        if self._rank is None:
            self._rank = rank_candidates(self.case, self.policy, self.now, self.attempts)
        return self._rank

    def count(self, *statuses):
        return sum(1 for a in self.attempts if a.status in statuses)

    @property
    def accepted_active(self):
        return sum(1 for a in self.attempts
                   if a.status == AttemptStatus.ACCEPTED and a.fulfilment != Fulfilment.NOT_DONATED)

    @property
    def pending(self):
        return self.count(*PENDING_ATTEMPT_STATUSES)

    @property
    def stage_name(self):
        i = self.case.current_stage_index
        return self.policy.stages[i].name if 0 <= i < len(self.policy.stages) else 'no stage reached yet'

    def label(self, attempt):
        if attempt.sim_donor_id:
            return f'{attempt.sim_donor.code} (fictional)'
        from .candidates import privacy_name
        u = attempt.donor.user
        return f'{privacy_name(u.first_name, u.last_name, "Donor")} (#{attempt.donor_id})'


