def known_facts(ctx):
    c, p = ctx.case, ctx.policy
    facts = [
        f'Request {c.reference}: {c.units_requested} unit(s) of {c.blood_group} at {c.hospital_name}, urgency {c.urgency}.',
        f'Coordination target: {c.target_volunteers} volunteer(s) ({c.units_requested} unit(s) x '
        f'{p.volunteers_per_unit} per unit). Volunteers are a coordination count, not confirmed blood units.',
        f'Volunteers who have accepted: {ctx.accepted_active}. Remaining coordination need: {c.remaining_coordination_need}.',
        f'Alerts issued: {len(ctx.attempts)} in {c.batches_created} batch(es); '
        f'{ctx.pending} awaiting a response, {ctx.count(AttemptStatus.DECLINED)} declined, '
        f'{ctx.count(AttemptStatus.NO_RESPONSE)} with no response inside the window (availability unknown).',
        f'Current status: {c.get_status_display()}. Search stage reached: {ctx.stage_name}.',
    ]
    pending_ver = sum(1 for a in ctx.attempts if a.fulfilment == Fulfilment.VERIFICATION_PENDING)
    confirmed = sum(1 for a in ctx.attempts if a.fulfilment == Fulfilment.DONATION_CONFIRMED)
    facts.append(f'Hospital verification pending: {pending_ver}. Donation outcomes confirmed by the hospital: {confirmed}.')
    if c.is_terminal:
        facts.append(f'The request is closed ({c.get_status_display()}): {c.closure_reason}')
    return facts


def unknowns(ctx):
    c = ctx.case
    out = []
    if c.is_simulation:
        out.append('Everything in this case is fictional: donors, hospital, responses and any inventory figures.')
    else:
        out.append('Live blood-bank / hospital stock levels are not connected, so stock is unknown.')
        out.append('Alert delivery is confirmed only when a donor opens the alert; there is no SMS or e-mail '
                   'gateway, so no external delivery receipts exist.')
    if c.hospital_lat is None or c.hospital_lng is None:
        out.append(f'The request has no coordinates; distances use the approximate reference point of '
                   f'{c.locality or "an unknown locality"}.')
    unknown_dist = sum(1 for a in ctx.rank.assessments if a.eligible and a.distance_km is None)
    if unknown_dist:
        out.append(f'{unknown_dist} eligible candidate(s) have no reliable coordinates: distance is Unknown and '
                   'they were placed by locality/city match.')
    unviewed = sum(1 for a in ctx.attempts if a.status == AttemptStatus.ALERTED)
    if unviewed:
        out.append(f'{unviewed} alert(s) have not been opened, so delivery is not confirmed.')
    lapsed = ctx.count(AttemptStatus.NO_RESPONSE)
    if lapsed:
        out.append(f'{lapsed} candidate(s) did not respond; whether they are available is unknown.')
    accepted = [a for a in ctx.attempts if a.status == AttemptStatus.ACCEPTED]
    if accepted and not any(a.fulfilment == Fulfilment.DONATION_CONFIRMED for a in accepted):
        out.append('No donation outcome has been confirmed by the hospital yet; accepting does not guarantee '
                   'attendance, eligibility or donation.')
    return out


