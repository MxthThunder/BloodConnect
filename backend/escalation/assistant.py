def rules_applied(ctx):
    p, c = ctx.policy, ctx.case
    out = [
        f'Response window for {c.urgency} requests: {p.wait_minutes(c.urgency)} min; an unanswered alert then becomes '
        '"no response (status unknown)", never "unavailable".',
        f'Minimum gap between batches while alerts are pending: {p.min_gap(c.urgency)} min. Batch limit: {p.max_batches}.',
        f'Expected acceptance per alert = (accepted + {p.assumed_response_rate:.0%} x {p.prior_weight}) / '
        f'(answered + {p.prior_weight}); batches are sized to cover the remaining need at that rate.',
        'Candidates are excluded if they lack consent, are declared unavailable, declined this request, were already '
        'contacted, or lack the information the matching rules need.',
    ]
    code = (c.last_decision or {}).get('reason_code')
    if code in _RULE_TEXT:
        out.insert(0, f'Last decision rule ({code}): {_RULE_TEXT[code]}')
    if not p.auto_escalate:
        out.append('Policy: expanding to a wider stage needs administrator approval (auto-escalation is off).')
    return out


def recommendations(ctx):
    """Next actions derived from the actual state. `action` values map to API operations."""
    c, p = ctx.case, ctx.policy
    recs = []
    if c.is_terminal:
        return [{'code': 'NONE', 'title': 'No action required', 'severity': 'info', 'action': None,
                 'reason': f'The request is {c.get_status_display().lower()}. {c.closure_reason}'}]
    last = c.last_decision or {}
    need = c.remaining_coordination_need
    avail = ctx.rank.available_by_stage[-1] if ctx.rank.available_by_stage else 0

    if c.status == CaseStatus.AWAITING_ESCALATION:
        recs.append({'code': 'APPROVE_ESCALATION', 'title': 'Approve the next expansion', 'severity': 'high',
                     'action': 'escalate',
                     'reason': last.get('reason') or 'Policy requires approval before the search area expands.'})
    elif c.status == CaseStatus.NEEDS_ADMIN_INTERVENTION:
        recs.append({'code': 'REVIEW_INTERVENTION', 'title': 'Administrator intervention required', 'severity': 'high',
                     'action': 'review', 'reason': last.get('reason') or 'The engine cannot progress alone.'})
        if avail > 0:
            recs.append({'code': 'APPROVE_EXTRA_BATCH', 'title': f'Alert up to {min(avail, 10)} more candidate(s)',
                         'severity': 'medium', 'action': 'escalate',
                         'reason': f'{avail} eligible, uncontacted candidate(s) remain; this bypasses the batch limit once.'})
        else:
            recs.append({'code': 'WIDEN_POLICY', 'title': 'Widen the search stages or contact the hospital blood bank',
                         'severity': 'medium', 'action': None,
                         'reason': 'No eligible candidate is left. Review Admin Settings (stages, radius) or coordinate '
                                   'directly with the hospital blood bank; this system has no stock integration.'})
    elif c.status == CaseStatus.VOLUNTEERS_SECURED:
        waiting = [a for a in ctx.attempts if a.status == AttemptStatus.ACCEPTED and a.fulfilment == Fulfilment.NONE]
        recs.append({'code': 'START_HOSPITAL_VERIFICATION',
                     'title': f'Send {len(waiting)} accepted volunteer(s) to hospital verification' if waiting
                     else 'Track hospital verification', 'severity': 'medium', 'action': 'fulfilment',
                     'reason': 'The volunteer target is reached, but volunteers are not donations: each must be '
                               'verified by the hospital and the donation outcome confirmed.'})
    elif c.status == CaseStatus.COLLECTING_RESPONSES:
        recs.append({'code': 'WAIT_FOR_RESPONSES', 'title': 'Monitor responses', 'severity': 'info', 'action': 'evaluate',
                     'reason': last.get('reason') or f'{ctx.pending} alert(s) are awaiting a response.'})
    elif c.status == CaseStatus.OPEN:
        recs.append({'code': 'RUN_ENGINE', 'title': 'Run the first evaluation', 'severity': 'medium', 'action': 'evaluate',
                     'reason': 'No outreach has been created yet.'})

    if need > 0 and c.status in (CaseStatus.COLLECTING_RESPONSES,) and avail > 0 and ctx.pending == 0:
        recs.append({'code': 'FORCE_EVALUATE', 'title': 'Run the engine now', 'severity': 'medium', 'action': 'evaluate',
                     'reason': 'All alerts are answered or lapsed and candidates remain; the engine will decide the next batch.'})
    if c.reviewed_at is None:
        recs.append({'code': 'MARK_REVIEWED', 'title': 'Record an administrator review', 'severity': 'info',
                     'action': 'review', 'reason': 'No administrator has reviewed this emergency yet.'})
    if c.status == CaseStatus.VOLUNTEERS_SECURED or any(a.fulfilment == Fulfilment.DONATION_CONFIRMED for a in ctx.attempts):
        recs.append({'code': 'RESOLVE', 'title': 'Resolve once the hospital confirms the requirement is met',
                     'severity': 'info', 'action': 'resolve',
                     'reason': 'Resolving needs a note; the request is never closed just because volunteers accepted.'})
    return recs


