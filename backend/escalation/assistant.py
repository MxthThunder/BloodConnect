def _answer_why_unresolved(ctx):
    c = ctx.case
    need = c.remaining_coordination_need
    if c.is_terminal:
        head = f'The request is closed as {c.get_status_display().lower()}: {c.closure_reason}'
    elif need > 0:
        head = (f'It is unresolved because {need} more volunteer(s) are needed ({ctx.accepted_active} of '
                f'{c.target_volunteers} have accepted). ' + ((c.last_decision or {}).get('reason') or ''))
    else:
        head = (f'The volunteer target ({c.target_volunteers}) has been reached, but the request is not resolved: '
                'accepted volunteers still need hospital verification and a confirmed donation outcome.')
    return head, known_facts(ctx), unknowns(ctx), rules_applied(ctx), [r['title'] + ' - ' + r['reason'] for r in recommendations(ctx)]


def _answer_why_prioritised(ctx):
    rows = [a for a in ctx.attempts if a.rank_position]
    rows.sort(key=lambda a: (a.batch.sequence, a.rank_position))
    facts = []
    for a in rows[:6]:
        top = sorted(a.score_breakdown or [], key=lambda b: b['points'], reverse=True)[:2]
        why = '; '.join(f"{b['label']}: {b['points']:g}/{b['max']:g} ({b['detail']})" for b in top)
        facts.append(f'Batch {a.batch.sequence} #{a.rank_position} {ctx.label(a)} - score {a.rank_score}%. {why}.')
    upcoming = ctx.rank.eligible[:3]
    for a in upcoming:
        facts.append(f'Next in line: {a.candidate.display_name} - score {a.score}%. {a.explanation}')
    w = ctx.policy.weights
    rules = [
        'Score = weighted points: ' + ', '.join(f'{k.replace("_", " ")} {v:g}' for k, v in w.items())
        + f' (total {ctx.policy.weight_total:g} = 100%). Weights are editable in Admin Settings.',
        'Ties are broken by the shorter known distance, then by candidate number.',
        "A candidate's past response behaviour is deliberately NOT used: it is not treated as current availability.",
        'Blood-group matching uses the platform table of declared groups; it is a matching criterion, not a '
        'transfusion-compatibility decision.',
    ]
    head = (f'{len(rows)} candidate(s) have been ranked and alerted so far.' if rows
            else 'No candidates have been alerted yet; the ranking below shows who is next in line.')
    unk = ['Distance is shown as Unknown where a donor has no reliable coordinates; no value is invented.',
           'Clinical suitability and eligibility of every candidate are unknown to this system.']
    return head, facts, unk, rules, []


def _answer_why_expanded(ctx):
    exp = [e for e in ctx.events if e.event_type in (EventType.SEARCH_EXPANDED, EventType.ESCALATION_TRIGGERED)]
    c = ctx.case
    if exp:
        head = f'The search was expanded {sum(1 for e in exp if e.event_type == EventType.SEARCH_EXPANDED)} time(s).'
        facts = [f'{e.event_time:%H:%M} - {e.decision_reason}' for e in exp]
    else:
        head = f'The search has not been expanded; it is still in {ctx.stage_name}.'
        nxt = c.current_stage_index + 1
        facts = []
        if 0 <= nxt < len(ctx.policy.stages):
            facts.append(f'Next stage would be "{ctx.policy.stages[nxt].name}".')
        facts.append((c.last_decision or {}).get('reason') or 'No decision recorded yet.')
    rules = [
        'Adaptive rule: expand only when the current stage has no eligible, uncontacted candidates left AND earlier '
        'alerts have been answered or have lapsed.',
        'Policy auto-escalation is ' + ('on.' if ctx.policy.auto_escalate else 'off: an administrator must approve expansion.'),
        'Stages: ' + '; '.join(f"{s.name} ({'no limit' if s.radius_km is None else str(s.radius_km) + ' km'}, "
                               f"{s.fallback_scope.lower()} fallback)" for s in ctx.policy.stages),
    ]
    return head, facts, unknowns(ctx), rules, []


def _answer_missing(ctx):
    u = unknowns(ctx)
    return (f'{len(u)} item(s) are unknown or unconfirmed.', known_facts(ctx)[:2], u, rules_applied(ctx)[:1], [])


def _answer_stages(ctx):
    p, c = ctx.policy, ctx.case
    facts = []
    for st in p.stages:
        batches = [b for b in c.batches.all() if b.stage_index == st.index]
        atts = [a for a in ctx.attempts if a.stage_index == st.index]
        if st.index < c.current_stage_index:
            state = 'completed (search moved beyond it)'
        elif st.index == c.current_stage_index:
            state = 'current'
        else:
            state = 'not reached'
        acc = sum(1 for a in atts if a.status == AttemptStatus.ACCEPTED)
        facts.append(f'{st.name}: {state}; {len(batches)} batch(es), {len(atts)} alert(s), {acc} accepted. '
                     f'Eligible candidates still uncontacted within this stage: {ctx.rank.available_by_stage[st.index]}.')
    head = f'{max(c.current_stage_index, -1) + 1} of {len(p.stages)} stage(s) reached; {c.batches_created} batch(es) created.'
    return head, facts, unknowns(ctx)[:3], rules_applied(ctx)[:2], []


def _answer_actions(ctx):
    recs = recommendations(ctx)
    head = recs[0]['title'] if recs else 'No actions.'
    return head, known_facts(ctx)[:3], unknowns(ctx)[:3], rules_applied(ctx)[:2], [f"{r['title']} - {r['reason']}" for r in recs]


def explain_experiment(exp):
    """Compare strategies using only the stored simulation results."""
    res = exp.results or {}
    strategies = res.get('strategies', {})
    if not strategies:
        return 'No results are stored for this experiment.', [], [], [], []
    facts, rows = [], {}
    for key, block in strategies.items():
        s = block['summary']
        rows[key] = s
        t = s['mean_time_to_target_minutes']
        facts.append(
            f"{block['label']}: target reached in {s['runs_target_reached']}/{s['runs']} run(s)"
            + (f", mean {t} min to target" if t is not None else ', never reached')
            + f"; avg {s['candidates_contacted']} candidates contacted, {s['outreach_batches']} batch(es), "
              f"{s['declines']} declines, {s['unanswered_alerts']} unanswered at stop, {s['unresolved_requests']} unresolved run(s)."
        )
    observations = []
    contacted = {k: v['candidates_contacted'] for k, v in rows.items()}
    lo = min(contacted.values())
    observations.append('Fewest candidates contacted: ' + ', '.join(strategies[k]['label'] for k, v in contacted.items() if v == lo) + f' ({lo}).')
    timed = {k: v['mean_time_to_target_minutes'] for k, v in rows.items() if v['mean_time_to_target_minutes'] is not None}
    if timed:
        fast = min(timed.values())
        observations.append('Fastest mean time to reach the volunteer target: ' + ', '.join(
            strategies[k]['label'] for k, v in timed.items() if v == fast) + f' ({fast} min).')
    else:
        observations.append('No strategy reached the volunteer target in this scenario.')
    resolved = {k: v['runs_target_reached'] for k, v in rows.items()}
    observations.append('Runs reaching the target: ' + '; '.join(f"{strategies[k]['label']} {v}/{rows[k]['runs']}" for k, v in resolved.items()) + '.')
    facts.extend(observations)
    unk = [res.get('caveat', ''), 'Real donor behaviour, hospital processing time and actual donation outcomes are unknown.',
           'Results depend on the scripted fictional dataset and the seeds used.']
    rules = ['All three strategies ran the same scenario, seed and donor dataset through the same engine.',
             'Baseline A alerts the whole eligible pool once; B contacts predefined stages on a timer; C sizes batches '
             'by remaining need and observed responses.']
    return f'Comparison for scenario "{Experiment(scenario=exp.scenario).get_scenario_display()}" over {len(exp.seeds)} seed(s).', facts, unk, rules, []


def _answer_strategy(ctx):
    run = ctx.case.simulation_run if ctx.case.is_simulation else None
    if run is not None and run.experiment_id:
        return explain_experiment(run.experiment)
    exp = None
    if run is not None:
        exp = Experiment.objects.filter(scenario=run.scenario, results__isnull=False).first()
    if exp:
        head, facts, unk, rules, sug = explain_experiment(exp)
        return 'Latest stored comparison for the same scenario: ' + head, facts, unk, rules, sug
    return ('No strategy comparison has been run for this case.', [],
            ['Comparisons exist only for fictional simulations; real emergencies cannot be re-run under other strategies.'],
            [], ['Open Strategy Comparison and run the scenario through all three strategies.'])


_INTENTS = {
    'why_unresolved': _answer_why_unresolved, 'why_prioritised': _answer_why_prioritised,
    'why_expanded': _answer_why_expanded, 'missing_information': _answer_missing,
    'stages_completed': _answer_stages, 'remaining_actions': _answer_actions,
    'strategy_comparison': _answer_strategy,
}


def _wrap(intent, question, head, facts, unk, rules, suggestions, simulation):
    return {
        'intent': intent, 'question': question, 'headline': head, 'known_facts': facts, 'unknowns': unk,
        'rules_applied': rules, 'suggestions': suggestions, 'is_simulation': simulation,
        'disclaimer': DISCLAIMER, 'generated_by': GENERATED_BY, 'generated_at': timezone.now(),
    }


def answer_case_question(case, question=None, intent=None):
    intent = intent if intent in _INTENTS else route_question(question)
    if intent is None:
        supported = '; '.join(q['label'] for q in QUESTIONS)
        return _wrap('unsupported', question,
                     "I can only answer questions about this request's recorded state. Try one of: " + supported,
                     [], [], [], [], case.is_simulation)
    ctx = CaseContext(case)
    label = next(q['label'] for q in QUESTIONS if q['key'] == intent)
    head, facts, unk, rules, sug = _INTENTS[intent](ctx)
    return _wrap(intent, question or label, head, facts, unk, rules, sug, case.is_simulation)


def answer_experiment_question(exp, question=None):
    head, facts, unk, rules, sug = explain_experiment(exp)
    return _wrap('strategy_comparison', question or 'How did the escalation strategies perform?', head, facts, unk, rules,
                 sug, True)
